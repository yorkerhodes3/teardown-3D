import test from 'node:test';
import assert from 'node:assert/strict';
import {createServer} from 'node:http';
import {readFile} from 'node:fs/promises';
import {chromium} from 'playwright';

test('rack row selection, per-rack BOMs and mobile controls', {timeout: 300000}, async (t) => {
  const html = await readFile(new URL('../../teardown-out/dist/lenovo-live.html', import.meta.url));
  const server = createServer((_, response) => { response.writeHead(200, {'Content-Type': 'text/html'}); response.end(html); });
  await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise((resolve) => server.close(resolve)));
  const browser = await chromium.launch({executablePath: process.env.CHROMIUM || undefined, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader']});
  t.after(() => browser.close());
  const page = await browser.newPage({viewport: {width: 1600, height: 900}});
  page.setDefaultTimeout(60000);
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  const ready = async () => {
    await page.waitForFunction(() => window.LIVE && window.SIM_SHOWN);
    await page.evaluate(() => { window.LIVE.st.setQuality({ao: false, shadow: 256, samples: 0}); window.LIVE.st.resize(1600, 900, 0.5); });
  };
  await page.goto(`http://127.0.0.1:${server.address().port}/`);
  await ready();
  await page.getByRole('button', {name: 'View rack row'}).click();
  const row = page.getByRole('region', {name: 'Data center rack row'});
  assert.equal(await row.getByRole('button').count(), 4);
  await page.screenshot({path: 'teardown-out/rack-row-desktop.png', timeout: 90000});
  // Click the second cabinet itself rather than the accessible button list.
  await Promise.all([page.waitForEvent('load'), page.locator('#gl').click({position: {x: 710, y: 430}})]);
  await ready();
  assert.equal(await page.evaluate(() => [...window.LIVE.st.rack.parts.keys()].filter((id) => /^gpu-\d+$/.test(id)).length), 4);
  await page.locator('.bom-dashboard > summary').click();
  const panel = page.locator('.bom-dashboard');
  await panel.getByLabel('Display title', {exact: true}).fill('Dell custom rack');
  await panel.locator(':scope > summary').click();
  await page.getByRole('button', {name: 'View rack row'}).click();
  page.once('dialog', (dialog) => dialog.dismiss());
  await row.getByRole('button', {name: /Lenovo AI Rack/}).click();
  assert.equal(await row.isVisible(), true);
  await page.getByRole('button', {name: 'Back to rack'}).click();
  await panel.locator(':scope > summary').click();
  assert.equal(await panel.getByLabel('Display title', {exact: true}).inputValue(), 'Dell custom rack');
  await Promise.all([page.waitForEvent('load'), panel.getByRole('button', {name: 'Apply BOM and reload'}).click()]);
  await ready();
  await page.getByRole('button', {name: 'View rack row'}).click();
  assert.match(await row.textContent(), /Dell custom rack/);
  await Promise.all([page.waitForEvent('load'), row.getByRole('button', {name: /Lenovo AI Rack/}).click()]);
  await ready();
  assert.equal(await page.evaluate(() => window.LIVE.st.rack.parts.has('gpu-7')), true);
  await page.getByRole('button', {name: 'View rack row'}).click();
  await Promise.all([page.waitForEvent('load'), row.getByRole('button', {name: /Dell custom rack/}).click()]);
  await ready();
  assert.ok(await page.getByText('Dell custom rack', {exact: false}).count());
  await page.setViewportSize({width: 390, height: 844});
  const mobile = page.getByRole('region', {name: 'Mobile teardown controls'});
  assert.equal(await mobile.isVisible(), true);
  await mobile.getByRole('button', {name: 'Next'}).click();
  await page.waitForFunction(() => window.LIVE.X > 0.1);
  await mobile.getByRole('button', {name: 'Risks on'}).click();
  assert.equal(await mobile.getByRole('button', {name: 'Risks off'}).isVisible(), true);
  await mobile.getByLabel('Inspect a component').selectOption({index: 1});
  await mobile.locator('summary').click();
  await page.waitForFunction(() => document.querySelector('[data-info]').textContent.includes('Example PCIe Accelerator'));
  await page.screenshot({path: 'teardown-out/rack-mobile.png', timeout: 90000});
  await page.getByRole('button', {name: 'View rack row'}).click();
  assert.equal(await mobile.isVisible(), false);
  assert.equal(await row.isVisible(), true);
  await page.getByRole('button', {name: 'Back to rack'}).click();
  assert.equal(await mobile.isVisible(), true);
  await page.locator('.bom-dashboard > summary').click();
  page.once('dialog', (dialog) => dialog.accept());
  await panel.getByLabel('Example rack BOM').selectOption('hpe-dl380a-gen11');
  await page.waitForFunction(() => document.querySelector('.dash-status').textContent.includes('loaded into the editor'));
  assert.equal(await panel.getByLabel('Display title', {exact: true}).inputValue(), 'HPE AI Rack');
  assert.match(await panel.locator('.dash-status').textContent(), /loaded into the editor/);
  assert.deepEqual(errors, []);
});
